// Builds prepare's WebAssembly into src/wasm/embedded.ts (generated, committed):
//   KERNELS_WASM   wasm/kernels.wat compiled with wabt: the bands' filter chains and the
//                  alignment's lag sums (SIMD)
//   PFFFTD_WASM    pffft, double precision, SIMD (npm pffft-ng, BSD-3-Clause; see
//                  THIRD_PARTY_NOTICES.md): the alignment's FFTs
//   PFFFT_WASM     pffft, single precision, SIMD: the overview spectrogram's FFTs
//   DECODERS_WASM  wasm/decoders.wasm, FLAC and MP3 (dr_flac, dr_mp3: public domain or MIT-0),
//                  compiled from wasm/decoders.c by build/build-decoders.mjs (needs zig)
// All as base64, so the bundle carries them to the main thread and to every worker and
// nothing has to find a .wasm file at run time. Run after editing kernels.wat:
//   npm run build:wasm -w packages/rt-dspplr-prepare
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import wabtInit from 'wabt';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const wabt = await wabtInit();
const wat = fs.readFileSync(path.join(root, 'wasm/kernels.wat'), 'utf8');
const parsed = wabt.parseWat('kernels.wat', wat, { simd: true });
parsed.validate();
const kernels = Buffer.from(parsed.toBinary({ log: false }).buffer);
parsed.destroy();
const pffftPath = require.resolve('pffft-ng/pffft-ng-f64.wasm');
const pffft = fs.readFileSync(pffftPath);
const pffftF = fs.readFileSync(require.resolve('pffft-ng/pffft-ng-f32.wasm'));
const decoders = fs.readFileSync(path.join(root, 'wasm/decoders.wasm'));
const pffftVersion = JSON.parse(fs.readFileSync(path.join(path.dirname(pffftPath), '..', 'package.json'), 'utf8')).version;

const out = `// GENERATED by build/build-wasm.mjs - do not edit.
// KERNELS_WASM: wasm/kernels.wat (this package's own code).
// PFFFTD_WASM, PFFFT_WASM: pffft ${pffftVersion} double and single precision (npm "pffft-ng"), BSD-3-Clause; the notice is in
// THIRD_PARTY_NOTICES.md (Copyright (c) 2024 John K. Luebs, 2020 Dario Mambro, 2019 Hayati
// Ayguen, 2013 Julien Pommier, 2004 the University Corporation for Atmospheric Research).
// DECODERS_WASM: wasm/decoders.c with dr_flac and dr_mp3 (David Reid; public domain or MIT-0).
export const KERNELS_WASM = ${JSON.stringify(kernels.toString('base64'))};
export const PFFFTD_WASM = ${JSON.stringify(pffft.toString('base64'))};
export const PFFFT_WASM = ${JSON.stringify(pffftF.toString('base64'))};
export const DECODERS_WASM = ${JSON.stringify(decoders.toString('base64'))};
`;
fs.mkdirSync(path.join(root, 'src/wasm'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/wasm/embedded.ts'), out);
console.log(`src/wasm/embedded.ts: kernels ${kernels.length} B, pffft-d ${pffft.length} B, pffft-f ${pffftF.length} B, decoders ${decoders.length} B`);
