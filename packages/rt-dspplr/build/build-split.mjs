// Compiles wasm/split.c (the tonal/atonal split of the stream engine's realtime stretch) and
// writes src/vendor/rtdSplit.ts: code for AudioWorkletGlobalScope that leaves the module's
// bytes in globalThis.__rtdSplitWasm (worklets have no atob: it carries its own decoder).
// Needs zig 0.13 (https://ziglang.org) on PATH, or its path in ZIG.
//   node build/build-split.mjs
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const zig = process.env.ZIG ?? 'zig';
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'rtd-split-')), 'split.wasm');
execFileSync(zig, [
    'cc', '-target', 'wasm32-wasi', '-mexec-model=reactor',
    '-O3', '-msimd128', '-ffp-contract=off', '-s',
    path.join(root, 'wasm/split.c'),
    '-o', out,
], { stdio: 'inherit' });
const bytes = fs.readFileSync(out);
fs.rmSync(path.dirname(out), { recursive: true, force: true });

const decoder = `(function () {
    var s = ${JSON.stringify(bytes.toString('base64'))};
    var t = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
    var map = new Uint8Array(128);
    for (var i = 0; i < 64; i++) map[t.charCodeAt(i)] = i;
    var pad = s.charAt(s.length - 1) === '=' ? (s.charAt(s.length - 2) === '=' ? 2 : 1) : 0;
    var out = new Uint8Array((s.length / 4) * 3 - pad);
    for (var i = 0, o = 0; i < s.length; i += 4) {
        var n = (map[s.charCodeAt(i)] << 18) | (map[s.charCodeAt(i + 1)] << 12) | (map[s.charCodeAt(i + 2)] << 6) | map[s.charCodeAt(i + 3)];
        if (o < out.length) out[o++] = n >> 16;
        if (o < out.length) out[o++] = (n >> 8) & 255;
        if (o < out.length) out[o++] = n & 255;
    }
    return out;
})()`;
const file = path.join(root, 'src/vendor/rtdSplit.ts');
fs.writeFileSync(file, `// GENERATED by build/build-split.mjs - do not edit.
// The tonal/atonal split of the stream engine's realtime stretch: wasm/split.c compiled to
// WebAssembly (${bytes.length} bytes), as code for AudioWorkletGlobalScope that leaves the
// module's bytes in globalThis.__rtdSplitWasm. Loaded lazily with the stretcher.
const code: string = ${JSON.stringify(`globalThis.__rtdSplitWasm = ${decoder};\n`)};
export default code;
`);
console.log(`${path.relative(root, file)}: ${bytes.length} B of WebAssembly`);
